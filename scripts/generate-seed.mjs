// Generates supabase/seed.sql from the bundled starter content, using the app's own
// tokenizer so word counts and IDs match exactly what the client computes.
// Run: npm run seed:generate
import { createServer } from 'vite';
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';

const server = await createServer({
  server: { middlewareMode: true },
  appType: 'custom',
  logLevel: 'error',
  optimizeDeps: { noDiscovery: true, include: [] },
});
try {
  const { STARTER_STORIES } = await server.ssrLoadModule('/src/content/starterStories.ts');
  const { STARTER_VOCABULARY } = await server.ssrLoadModule('/src/content/starterVocabulary.ts');
  const { tokenizePassage, TOKENIZER_VERSION } = await server.ssrLoadModule('/src/text/tokenize.ts');

  const q = (value) => {
    if (value === null || value === undefined) return 'null';
    if (typeof value === 'number' || typeof value === 'boolean') return String(value);
    const text = String(value);
    if (text.includes('$seed$')) throw new Error('Unexpected delimiter in content');
    return `$seed$${text}$seed$`;
  };

  const lines = [
    '-- GENERATED by scripts/generate-seed.mjs from src/content/*. Do not edit by hand.',
    '-- Development seed: the starter story library and DRAFT vocabulary only.',
    '-- It contains no learners, sessions, results or other learner activity.',
    '',
    'begin;',
    '',
  ];

  for (const s of STARTER_STORIES) {
    lines.push(
      `insert into public.stories (id, owner_id, visibility, status, draft_title, draft_body, draft_summary, language, grade_level, topic, revision)`,
      `values (${q(s.storyId)}, null, 'library', 'published', ${q(s.title)}, ${q(s.body)}, ${q(s.summary)}, ${q(s.language)}, ${s.gradeLevel}, ${q(s.topic)}, 1)`,
      `on conflict (id) do nothing;`,
    );
  }
  lines.push('');
  for (const s of STARTER_STORIES) {
    const wordCount = tokenizePassage(s.body, s.language).words.length;
    const hash = createHash('sha256').update(`${s.title}\n${s.body}`, 'utf8').digest('hex');
    lines.push(
      `insert into public.story_versions (id, story_id, version_number, title, body, summary, language, grade_level, topic, tokenizer_version, word_count, content_sha256)`,
      `values (${q(s.id)}, ${q(s.storyId)}, ${s.versionNumber}, ${q(s.title)}, ${q(s.body)}, ${q(s.summary)}, ${q(s.language)}, ${s.gradeLevel}, ${q(s.topic)}, ${TOKENIZER_VERSION}, ${wordCount}, ${q(hash)})`,
      `on conflict (id) do nothing;`,
      `update public.stories set published_version_id = ${q(s.id)} where id = ${q(s.storyId)} and published_version_id is null;`,
    );
  }
  lines.push('');
  for (const v of STARTER_VOCABULARY) {
    lines.push(
      `insert into public.vocabulary_entries (id, language, headword, normalized, part_of_speech, definition, example, syllables, syllables_verified, review_status)`,
      `values (${q(v.id)}, ${q(v.language)}, ${q(v.headword)}, ${q(v.normalized)}, ${q(v.partOfSpeech)}, ${q(v.definition)}, ${q(v.example)}, null, false, 'draft')`,
      `on conflict (language, normalized) do nothing;`,
    );
  }
  lines.push('', 'commit;', '');
  writeFileSync('supabase/seed.sql', lines.join('\n'));
  console.log(`supabase/seed.sql written: ${STARTER_STORIES.length} stories, ${STARTER_VOCABULARY.length} vocabulary entries.`);
} finally {
  await server.close();
}
